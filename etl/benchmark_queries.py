"""Time the queries the dashboard and the model run (numbers for the paper's database section).

    python -m etl.benchmark_queries            # 30 timed runs per query after 3 warm-ups

Writes paper/benchmark_results.csv and paper/benchmark_results.md. The .md records the machine,
PostgreSQL and TimescaleDB versions, so the numbers can be quoted honestly. Run it on the
docker-compose database (TimescaleDB), not on a different setup, before quoting any number.
Each timing is wall-clock time from sending the query to having every row as a Python object.
"""
from __future__ import annotations

import argparse
import datetime as dt
import platform
import statistics
import time

import pandas as pd

from dashboard import queries as q
from etl.db import ROOT, connect

OUT = ROOT / "paper"

LIVE_JOIN = """
SELECT w.ts, avg(w.wind_speed) AS wind_speed, avg(w.temperature) AS temperature,
       avg(w.humidity) AS humidity, max(p.generation_mu) AS generation_mu
FROM raw_weather_readings w
LEFT JOIN power_output p ON p.ts = w.ts AND p.station_id = 1
WHERE w.station_id IN (2, 3, 4)
GROUP BY w.ts ORDER BY w.ts
"""

CASES = [
    ("full daily feature table (materialized view)", "model reads all 1,826 days",
     lambda c: q.daily_features(c)),
    ("same table, computed live from raw tables", "comparison with the view",
     lambda c: c.execute(LIVE_JOIN).fetchall()),
    ("one-year slice of the view", "dashboard date filter",
     lambda c: q.daily_features(c, "2023-01-01", "2023-12-31")),
    ("weekly features (materialized view)", "weekly aggregates",
     lambda c: q.weekly_features(c)),
    ("monthly climatology", "overview bar charts",
     lambda c: q.monthly_climatology(c)),
    ("raw weather, one station, one year", "hypertable range scan",
     lambda c: c.execute("SELECT * FROM raw_weather_readings WHERE station_id = 2 "
                         "AND ts >= '2023-01-01' AND ts < '2024-01-01'").fetchall()),
    ("change factors: monthly, all models, one case", "climate page chart",
     lambda c: q.monthly_factors(c, "ssp245", 2050)),
    ("change factors: annual, all cases", "climate page table",
     lambda c: q.annual_factors_all(c)),
    ("table row counts", "status page",
     lambda c: q.table_counts(c)),
]


def timeit(fn, conn, warmup: int, runs: int) -> list[float]:
    for _ in range(warmup):
        fn(conn)
    out = []
    for _ in range(runs):
        t = time.perf_counter()
        fn(conn)
        out.append((time.perf_counter() - t) * 1000)
    return out


def main(runs: int = 30, warmup: int = 3) -> pd.DataFrame:
    rows = []
    with connect() as conn:
        version = conn.execute("SHOW server_version").fetchone()[0]
        ts = conn.execute("SELECT extversion FROM pg_extension WHERE extname = 'timescaledb'").fetchone()
        sizes = dict(conn.execute("SELECT 'mv_daily', count(*) FROM mv_daily_features").fetchall())
        for name, purpose, fn in CASES:
            t = timeit(fn, conn, warmup, runs)
            rows.append({
                "query": name, "used_for": purpose, "runs": runs,
                "median_ms": round(statistics.median(t), 2),
                "p95_ms": round(sorted(t)[max(0, int(0.95 * len(t)) - 1)], 2),
                "min_ms": round(min(t), 2), "max_ms": round(max(t), 2),
            })
    df = pd.DataFrame(rows)
    OUT.mkdir(exist_ok=True)
    df.to_csv(OUT / "benchmark_results.csv", index=False)
    table = "| Query | Used for | Median (ms) | 95th pct (ms) | Min | Max |\n|---|---|---:|---:|---:|---:|\n" + "\n".join(
        f"| {r.query} | {r.used_for} | {r.median_ms} | {r.p95_ms} | {r.min_ms} | {r.max_ms} |" for r in df.itertuples())
    (OUT / "benchmark_results.md").write_text(
        f"""# Query benchmark

Generated by `python -m etl.benchmark_queries` on {dt.datetime.now(dt.timezone.utc):%Y-%m-%d %H:%M} UTC. Do not edit by hand.

- PostgreSQL {version}; TimescaleDB {ts[0] if ts else 'NOT INSTALLED (numbers are not for the paper)'}
- Python {platform.python_version()} on {platform.system()} {platform.machine()}
- {runs} timed runs per query after {warmup} warm-up runs; time = send query until all rows are Python objects
- Data: {sizes.get('mv_daily', '?')} daily rows (state level), 3 weather points, 5 years. With data this small every query takes
  milliseconds, so the dashboard stays interactive. Compare the view with the live join in the table; report whatever
  difference it shows, do not assume the view is faster.

{table}
""")
    print((OUT / "benchmark_results.md").read_text())
    return df


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--runs", type=int, default=30)
    a = p.parse_args()
    main(a.runs)
