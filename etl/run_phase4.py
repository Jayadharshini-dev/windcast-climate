"""Phase 4 pipeline: NEX-GDDP climate data -> climate_scenarios -> change-factor views -> hand-off files.

    python -m etl.run_phase4 --ee-project YOUR_PROJECT_ID     # fetch from Earth Engine, then load
    python -m etl.run_phase4 --skip-fetch                      # load the committed CSV only (no account needed)

Outputs (data/golden/):
  nexgddp_monthly_means.csv           raw window means per model/scenario/window/month/point (fetch output)
  change_factors_region_monthly.csv   what the model applies: monthly factors per climate model (state level)
  climate_load_report.md              every count and check, generated by this script
"""
from __future__ import annotations

import argparse
import datetime as dt
import json

import pandas as pd

from etl import fetch_nexgddp, load_nexgddp
from etl.db import ROOT, connect

MIGRATIONS = ROOT / "db" / "migrations"
GOLDEN = ROOT / "data" / "golden"


def apply_migrations() -> list[str]:
    applied = []
    with connect() as conn:
        for f in sorted(MIGRATIONS.glob("*.sql")):
            conn.execute(f.read_text())  # all migrations are idempotent (CREATE OR REPLACE)
            applied.append(f.name)
        conn.commit()
    return applied


def export_and_summarise() -> tuple[dict, pd.DataFrame]:
    with connect() as conn:
        cur = conn.execute(
            "SELECT region, scenario, target_year, window_start, window_end, month, climate_model, n_points, "
            "wind_ratio, temp_delta_c, humidity_delta_pct FROM v_change_factors_region "
            "ORDER BY scenario, target_year, climate_model, month NULLS LAST")
        cf = pd.DataFrame(cur.fetchall(), columns=[c.name for c in cur.description])
    GOLDEN.mkdir(parents=True, exist_ok=True)
    cf.round(5).to_csv(GOLDEN / "change_factors_region_monthly.csv", index=False)

    ann = cf[cf["month"].isna()]
    summary = {}
    for (scen, year), g in ann.groupby(["scenario", "target_year"]):
        summary[f"{scen}_{year}"] = {
            "n_models": int(g["climate_model"].nunique()),
            "wind_ratio_mean_min_max": [round(float(g["wind_ratio"].mean()), 4), round(float(g["wind_ratio"].min()), 4),
                                         round(float(g["wind_ratio"].max()), 4)],
            "temp_delta_c_mean_min_max": [round(float(g["temp_delta_c"].mean()), 2), round(float(g["temp_delta_c"].min()), 2),
                                           round(float(g["temp_delta_c"].max()), 2)],
            "humidity_delta_pct_mean_min_max": [round(float(g["humidity_delta_pct"].mean()), 2),
                                                 round(float(g["humidity_delta_pct"].min()), 2),
                                                 round(float(g["humidity_delta_pct"].max()), 2)],
        }
    return summary, cf


def main(ee_project: str | None, skip_fetch: bool, workers: int = 4) -> None:
    print("1/4 applying db/migrations ...")
    print("   ", apply_migrations())
    fetched = None
    if not skip_fetch:
        if not ee_project:
            raise SystemExit("Pass --ee-project YOUR_PROJECT_ID, or use --skip-fetch to load the committed CSV.")
        print("2/4 fetching from Google Earth Engine (resumable) ...")
        fetched = fetch_nexgddp.main(ee_project, workers=workers)
    else:
        print("2/4 fetch skipped (using the existing CSV)")
    print("3/4 loading into climate_scenarios ...")
    loaded = load_nexgddp.main()
    print("4/4 exporting change factors ...")
    summary, cf = export_and_summarise()

    text = f"""# Phase 4 climate load report

Generated by `python -m etl.run_phase4` on {dt.datetime.now(dt.timezone.utc):%Y-%m-%d %H:%M} UTC. Do not edit by hand.

Models requested: {fetch_nexgddp.MODELS}
Windows: {fetch_nexgddp.WINDOWS}

## Load
```
{json.dumps(loaded, indent=2, default=str)}
```

## Ensemble summary of annual change factors (state level, [mean, min, max] across models)
Wind = ratio future/baseline; temperature in deg C and humidity in % points = difference. Baseline 1995-2014.
```
{json.dumps(summary, indent=2)}
```
"""
    (GOLDEN / "climate_load_report.md").write_text(text)
    print(text)


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--ee-project", help="Google Cloud project id registered for Earth Engine")
    p.add_argument("--skip-fetch", action="store_true", help="load data/golden/nexgddp_monthly_means.csv only")
    p.add_argument("--workers", type=int, default=4)
    a = p.parse_args()
    main(a.ee_project, a.skip_fetch, a.workers)
