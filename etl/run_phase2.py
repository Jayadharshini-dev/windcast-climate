"""Phase 2 pipeline: load CEA + ERA5, refresh views, export the golden dataset (gate G1).

    python -m etl.run_phase2

Outputs:
  data/golden/tn_daily_golden.csv   one row per day in the CEA span (the Day 2 hand-off file)
  data/golden/load_report.md        every count and check below, generated by this script
"""
import datetime as dt
import json

import pandas as pd

from etl import load_cea, load_era5
from etl.db import ROOT, connect

GOLDEN_DIR = ROOT / "data" / "golden"


def refresh_views() -> None:
    with connect() as conn:
        conn.execute("REFRESH MATERIALIZED VIEW mv_daily_features")
        conn.execute("REFRESH MATERIALIZED VIEW mv_weekly_features")


def export_golden(first_day: str, last_day: str) -> tuple[pd.DataFrame, dict]:
    with connect() as conn:
        cur = conn.execute(
            """
            SELECT ts, region, wind_speed, temperature, humidity, n_points,
                   generation_mu, capacity_mw, capacity_factor
            FROM mv_daily_features
            WHERE region = 'Tamil Nadu' AND ts BETWEEN %s AND %s
            ORDER BY ts
            """,
            (first_day, last_day),
        )
        df = pd.DataFrame(cur.fetchall(), columns=[c.name for c in cur.description])
    GOLDEN_DIR.mkdir(parents=True, exist_ok=True)
    df.round(4).to_csv(GOLDEN_DIR / "tn_daily_golden.csv", index=False)

    usable = df.dropna(subset=["generation_mu", "wind_speed"])
    ts = pd.to_datetime(df["ts"])
    checks = {
        "rows": len(df),
        "rows_with_generation": int(df["generation_mu"].notna().sum()),
        "rows_missing_generation": int(df["generation_mu"].isna().sum()),
        "rows_with_all_3_weather_points": int((df["n_points"] == 3).sum()),
        "rows_usable_for_training": len(usable),
        "corr_wind_vs_generation": round(float(usable["wind_speed"].corr(usable["generation_mu"])), 3),
        "monthly_mean_generation_mu": df.groupby(ts.dt.month)["generation_mu"].mean().round(1).to_dict(),
        "monthly_mean_wind_ms": df.groupby(ts.dt.month)["wind_speed"].mean().round(2).to_dict(),
    }
    return df, checks


def write_report(cea: dict, era5: dict, golden: dict) -> str:
    def block(d):
        return "```\n" + json.dumps(d, indent=2, default=str) + "\n```"

    text = f"""# Phase 2 load report

Generated by `python -m etl.run_phase2` on {dt.datetime.now(dt.timezone.utc):%Y-%m-%d %H:%M} UTC. Do not edit by hand.

## CEA generation (power_output, station 1 TN_STATE)
{block(cea)}

## ERA5 weather (raw_weather_readings, stations 2-4)
{block(era5)}

## Golden dataset (data/golden/tn_daily_golden.csv, from mv_daily_features)
{block(golden)}
"""
    (GOLDEN_DIR / "load_report.md").write_text(text)
    return text


def main() -> None:
    print("1/4 loading CEA generation ...")
    cea = load_cea.main()
    print("2/4 loading ERA5 weather (downloads on first run) ...")
    era5 = load_era5.main()
    print("3/4 refreshing views ...")
    refresh_views()
    print("4/4 exporting golden dataset ...")
    _, golden = export_golden(cea["first_day"], cea["last_day"])
    print(write_report(cea, era5, golden))


if __name__ == "__main__":
    main()
